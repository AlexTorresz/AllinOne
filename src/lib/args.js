'use strict';

// Divide uma linha de argumentos respeitando aspas: -windowed "C:\meu mod" -novid
function splitArgs(line) {
  const out = [];
  if (!line) return out;
  let cur = '';
  let quote = null;
  let has = false;
  for (const ch of String(line)) {
    if (quote) {
      if (ch === quote) quote = null;
      else cur += ch;
    } else if (ch === '"' || ch === "'") {
      quote = ch;
      has = true;
    } else if (/\s/.test(ch)) {
      if (cur || has) { out.push(cur); cur = ''; has = false; }
    } else {
      cur += ch;
    }
  }
  if (cur || has) out.push(cur);
  return out;
}

module.exports = { splitArgs };
